"""
Разбор строки вроде «120 кава» или «таксі 85.50».

Смысл бота в том, что писать надо одно короткое сообщение, без меню
и без выбора категории. Значит, разбор должен прощать всё: любой
порядок слов, запятую вместо точки, лишние пробелы, эмодзи.

Категория угадывается по словам, а не спрашивается. Если угадали
неверно, человек жмёт одну кнопку — и бот запоминает это слово за
нужной категорией. Со второй-третьей поправки он перестаёт ошибаться
на вашем словаре, а не на общем.
"""
import re
import unicodedata

CATEGORIES = {
    'їжа':       ('кава', 'кофе', 'обід', 'обед', 'їжа', 'еда', 'продукти', 'сільпо',
                  'атб', 'ашан', 'новус', 'варус', 'сніданок', 'вечеря', 'піца',
                  'суші', 'ресторан', 'кафе', 'булочна', 'хліб', 'молоко'),
    'транспорт': ('таксі', 'такси', 'убер', 'uber', 'болт', 'bolt', 'уклон', 'метро',
                  'автобус', 'маршрутка', 'бензин', 'паливо', 'заправка', 'квиток'),
    'житло':     ('оренда', 'квартира', 'комуналка', 'світло', 'газ', 'вода',
                  'інтернет', 'опалення'),
    'здоров’я':  ('аптека', 'ліки', 'лікар', 'стоматолог', 'аналізи', 'клініка'),
    'одяг':      ('одяг', 'взуття', 'куртка', 'кросівки', 'футболка', 'джинси'),
    'розваги':   ('кіно', 'бар', 'концерт', 'гра', 'підписка', 'netflix', 'spotify',
                  'книга', 'театр'),
    'зв’язок':   ('київстар', 'водафон', 'лайфселл', 'мобільний', 'телефон'),
    'інше':      (),
}

# Слово → категория. Строится один раз, дальше только читается.
WORD_MAP = {word: cat for cat, words in CATEGORIES.items() for word in words}

AMOUNT = re.compile(r'(?<![\d.,])(\d{1,7})(?:[.,](\d{1,2}))?(?![\d])')


def clean(text):
    """Убираем эмодзи и лишние знаки, оставляем буквы, цифры и пробелы."""
    out = []
    for ch in text.lower():
        if ch.isalnum() or ch.isspace() or ch in '.,\'’-':
            out.append(ch)
        elif unicodedata.category(ch).startswith('P'):
            out.append(' ')
    return re.sub(r'\s+', ' ', ''.join(out)).strip()


def parse(text, learned=None):
    """
    Возвращает (копейки, заметка, категория) или None, если суммы нет.
    learned — словарь слово→категория, выученный от этого пользователя;
    он главнее общего, потому что «зерно» у кофейни и у фермера — разное.
    """
    text = clean(text)
    m = AMOUNT.search(text)
    if not m:
        return None

    whole, cents = m.group(1), m.group(2) or '0'
    kop = int(whole) * 100 + int(cents.ljust(2, '0'))
    if kop <= 0:
        return None

    note = (text[:m.start()] + ' ' + text[m.end():]).strip()
    note = re.sub(r'\s+', ' ', note)

    words = note.split()
    for word in words:
        if learned and word in learned:
            return kop, note, learned[word]
    for word in words:
        if word in WORD_MAP:
            return kop, note, WORD_MAP[word]
    # Украинский склоняется, и «кавуська» словарём не ловится.
    # Сравниваем основы: у более короткого из двух слов отбрасываем
    # последнюю букву и смотрим, совпадает ли начало. Правило грубое,
    # но у бота есть кнопка исправления, а у словаря — обучение.
    for word in words:
        for known, cat in WORD_MAP.items():
            n = min(len(word), len(known))
            if n >= 4 and word[:n - 1] == known[:n - 1]:
                return kop, note, cat
    return kop, note, 'інше'


def money(kop):
    return f'{kop // 100},{kop % 100:02d} ₴'
