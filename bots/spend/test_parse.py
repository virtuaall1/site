"""Проверка разбора. Запускается сам по себе: python3 test_parse.py"""
import sys
sys.path.insert(0, __file__.rsplit('/', 1)[0])
from parse import parse   # noqa: E402

CASES = [
    ('120 кава',            (12000, 'кава', 'їжа')),
    ('кава 120',            (12000, 'кава', 'їжа')),
    ('таксі 85.50',         (8550, 'таксі', 'транспорт')),
    ('85,5 таксі',          (8550, 'таксі', 'транспорт')),
    ('  1200   оренда  ',   (120000, 'оренда', 'житло')),
    ('☕ 45 кава на виніс',  (4500, 'кава на виніс', 'їжа')),
    ('300 щось незрозуміле', (30000, 'щось незрозуміле', 'інше')),
    ('аптека 260',          (26000, 'аптека', 'здоров’я')),
    ('кавуська 60',         (6000, 'кавуська', 'їжа')),      # частичное совпадение
    ('просто текст',        None),
    ('0 кава',              None),
]

ok = True
for text, want in CASES:
    got = parse(text)
    good = got == want
    ok &= good
    print(('  ок  ' if good else 'ПАДАЕТ') + f'  {text!r}')
    if not good:
        print(f'        ожидали {want}, получили {got}')

# выученное слово главнее общего словаря
got = parse('90 зерно', learned={'зерно': 'їжа'})
good = got == (9000, 'зерно', 'їжа')
ok &= good
print(('  ок  ' if good else 'ПАДАЕТ') + '  выученное слово перебивает словарь')

print('\nвсё сошлось' if ok else '\nесть расхождения')
sys.exit(0 if ok else 1)
